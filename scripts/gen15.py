# ---------- 注入 guides.js ----------
BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
path = os.path.join(BASE, "content", "guides.js")
src = open(path, encoding="utf-8").read()

# 生成 JS 对象字面量（json.dumps 输出合法 JS 对象）
def to_js(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2)

blocks_js = ",\n".join(to_js(g) for g in G)

# 在数组闭合 ]; （getGuide 之前）插入
marker = "\n];\n\nexport function getGuide"
idx = src.find(marker)
if idx == -1:
    raise SystemExit("找不到数组闭合标记")
insert_at = idx  # marker 以 \n]; 开头，我们在 ]; 之前插入
new_src = src[:insert_at] + ",\n" + blocks_js + src[insert_at:]

open(path, "w", encoding="utf-8").write(new_src)
print("已注入 %d 篇攻略，guides.js 现约 %d 字符" % (len(G), len(new_src)))
